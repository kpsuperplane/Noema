//! Web frontend protocol types and TypeScript binding generation.

use std::{fs, path::Path};

use serde::{Deserialize, Serialize};
use ts_rs::{Config as TsConfig, TS};

use crate::{AgentStatus, StartedConversation, TurnTranscriptItem};

const GENERATED_HEADER: &str = "/* @generated by `cargo run --manifest-path crates/noema-core/Cargo.toml --bin export_frontend_types`. Do not edit by hand. */\n\n";

/// Local service status shown by the web UI.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(rename_all = "snake_case")]
pub enum WebLocalServiceStatus {
    /// The local Noema daemon is running.
    Running,
}

/// Assistant connection exposed to the web UI.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(rename_all = "snake_case")]
pub enum WebAssistantConnection {
    /// The daemon is using Codex app-server for chat turns.
    Codex,
}

/// Memory storage readiness shown by the web UI.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(rename_all = "snake_case")]
pub enum WebMemoryStorageStatus {
    /// The canonical memory store is ready.
    Ready,
    /// The canonical memory store is being initialized.
    Initializing,
}

/// Status returned by `GET /api/status`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(rename_all = "snake_case")]
pub struct WebStatus {
    local_service: WebLocalServiceStatus,
    assistant_connection: WebAssistantConnection,
    memory_storage: WebMemoryStorageStatus,
}

impl WebStatus {
    /// Build a status response for the local web UI.
    #[must_use]
    pub(crate) const fn new(memory_storage: WebMemoryStorageStatus) -> Self {
        Self {
            local_service: WebLocalServiceStatus::Running,
            assistant_connection: WebAssistantConnection::Codex,
            memory_storage,
        }
    }
}

/// Messages accepted from the web frontend over `/api/chat/ws`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(tag = "type", rename_all = "snake_case")]
#[ts(tag = "type", rename_all = "snake_case")]
pub enum WebClientMessage {
    /// Start a new daemon-backed conversation.
    #[serde(rename = "conversation_start")]
    #[ts(rename = "conversation_start")]
    Start {
        /// Optional model override.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        #[ts(optional)]
        model: Option<String>,
        /// Optional working directory for the conversation.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        #[ts(optional)]
        cwd: Option<String>,
    },
    /// Start or resume the durable primary conversation.
    #[serde(rename = "primary_conversation_start")]
    #[ts(rename = "primary_conversation_start")]
    StartPrimary {
        /// Optional model override.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        #[ts(optional)]
        model: Option<String>,
        /// Optional working directory for the conversation.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        #[ts(optional)]
        cwd: Option<String>,
    },
    /// Send one user turn to an existing conversation.
    #[serde(rename = "conversation_turn")]
    #[ts(rename = "conversation_turn")]
    Turn {
        /// Daemon conversation id.
        conversation_id: String,
        /// User input.
        input: String,
        /// Frontend-generated id for correlating optimistic UI state.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        #[ts(optional)]
        client_message_id: Option<String>,
    },
    /// End a conversation and release provider state.
    #[serde(rename = "conversation_end")]
    #[ts(rename = "conversation_end")]
    End {
        /// Daemon conversation id.
        conversation_id: String,
    },
}

/// Messages emitted to the web frontend over `/api/chat/ws`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
#[serde(tag = "type", rename_all = "snake_case")]
#[ts(tag = "type", rename_all = "snake_case")]
pub enum WebServerMessage {
    /// Generic success response.
    Ok {
        /// Optional success message.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        #[ts(optional)]
        message: Option<String>,
    },
    /// Conversation start response.
    ConversationStarted {
        /// Daemon conversation id.
        conversation_id: String,
        /// Provider used for the conversation.
        provider: String,
    },
    /// One persisted conversation item emitted by an in-progress turn.
    ConversationItem {
        /// Daemon conversation id.
        conversation_id: String,
        /// Frontend-generated id originally sent with the user message.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        #[ts(optional)]
        client_message_id: Option<String>,
        /// Durable conversation item id.
        item_id: String,
        /// Durable conversation turn id.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        #[ts(optional)]
        turn_id: Option<String>,
        /// Transcript item to render in chat.
        item: TurnTranscriptItem,
    },
    /// Live agent status changed for a conversation.
    AgentStatusChanged {
        /// Daemon conversation id.
        conversation_id: String,
        /// Current agent coordination status.
        status: AgentStatus,
    },
    /// Durable replay for a conversation transcript.
    ConversationReplay {
        /// Daemon conversation id.
        conversation_id: String,
        /// Persisted conversation items in replay order.
        items: Vec<WebConversationItem>,
    },
    /// Turn completion response.
    TurnCompleted {
        /// Daemon conversation id.
        conversation_id: String,
        /// Frontend-generated id originally sent with the user message.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        #[ts(optional)]
        client_message_id: Option<String>,
    },
    /// Error response returned over the web protocol.
    Error {
        /// Stable machine-readable error code.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        #[ts(optional)]
        code: Option<WebErrorCode>,
        /// Human-readable error message.
        message: String,
    },
}

/// Stable machine-readable web protocol error code.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(rename_all = "snake_case")]
pub enum WebErrorCode {
    /// Chat cannot start until onboarding is complete.
    NotOnboarded,
}

/// One persisted conversation item in web replay.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
pub struct WebConversationItem {
    /// Durable conversation item id.
    item_id: String,
    /// Durable conversation turn id.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    turn_id: Option<String>,
    /// Transcript item to render in chat.
    item: TurnTranscriptItem,
}

impl WebConversationItem {
    pub(crate) fn new(item_id: String, turn_id: Option<String>, item: TurnTranscriptItem) -> Self {
        Self {
            item_id,
            turn_id,
            item,
        }
    }
}

impl WebServerMessage {
    pub(crate) fn conversation_started(started: StartedConversation) -> Self {
        Self::ConversationStarted {
            conversation_id: started.conversation_id,
            provider: "codex".to_string(),
        }
    }
}

/// Request body for starting a provider authentication attempt.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(deny_unknown_fields)]
pub struct StartProviderAuthAttemptRequest {
    /// Provider family, such as `codex`.
    pub provider_kind: String,
    /// Stable provider account id.
    pub provider_account_id: String,
    /// Requested authentication method.
    pub method: crate::ProviderAuthMethod,
}

/// Return the generated TypeScript binding file content.
#[must_use]
pub fn generated_frontend_typescript() -> String {
    let config = TsConfig::default();
    let declarations = [
        exported_decl::<AgentStatus>(&config),
        exported_decl::<crate::TurnActivityStatus>(&config),
        exported_decl::<TurnTranscriptItem>(&config),
        exported_decl::<WebLocalServiceStatus>(&config),
        exported_decl::<WebAssistantConnection>(&config),
        exported_decl::<WebMemoryStorageStatus>(&config),
        exported_decl::<WebStatus>(&config),
        exported_decl::<WebConversationItem>(&config),
        exported_decl::<WebClientMessage>(&config),
        exported_decl::<WebErrorCode>(&config),
        exported_decl::<WebServerMessage>(&config),
        exported_decl::<StartProviderAuthAttemptRequest>(&config),
        exported_decl::<crate::ProviderAuthMethod>(&config),
        exported_decl::<crate::ProviderAccountStatus>(&config),
        exported_decl::<crate::provider_auth::ProviderAuthAttemptStatus>(&config),
        exported_decl::<crate::provider_auth::ProviderAuthAttemptView>(&config),
        exported_decl::<crate::OnboardingStepStatus>(&config),
        exported_decl::<crate::OnboardingStep>(&config),
        exported_decl::<crate::OnboardingStatus>(&config),
    ];

    format!("{GENERATED_HEADER}{}\n", declarations.join("\n\n"))
}

/// Write generated TypeScript bindings to `path`.
///
/// # Errors
///
/// Returns an error when the output directory cannot be created or the file
/// cannot be written.
pub fn write_frontend_typescript(path: &Path) -> std::io::Result<()> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(path, generated_frontend_typescript())
}

fn exported_decl<T: TS>(config: &TsConfig) -> String {
    format!("export {}", T::decl(config))
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_frontend_types_are_current() {
        let expected = generated_frontend_typescript();
        let actual = include_str!("../web/src/generated/noema.ts");

        assert_eq!(
            actual, expected,
            "generated frontend types are stale; run `cargo run --manifest-path crates/noema-core/Cargo.toml --bin export_frontend_types`"
        );
    }

    #[test]
    fn web_client_message_supports_primary_conversation_start() {
        let message = serde_json::from_value::<WebClientMessage>(serde_json::json!({
            "type": "primary_conversation_start",
        }))
        .expect("message");

        assert_eq!(
            message,
            WebClientMessage::StartPrimary {
                model: None,
                cwd: None,
            }
        );
    }

    #[test]
    fn web_conversation_item_and_status_messages_serialize() {
        let message = WebServerMessage::ConversationItem {
            conversation_id: "conversation_1".to_string(),
            client_message_id: Some("client_1".to_string()),
            item_id: "item_1".to_string(),
            turn_id: Some("turn_1".to_string()),
            item: TurnTranscriptItem::AssistantText {
                text: "hello".to_string(),
            },
        };
        let encoded = serde_json::to_string(&message).expect("encode");
        assert!(encoded.contains(r#""type":"conversation_item""#));
        assert!(encoded.contains(r#""client_message_id":"client_1""#));
        assert!(encoded.contains(r#""item_id":"item_1""#));
        assert!(encoded.contains(r#""turn_id":"turn_1""#));
        let decoded: WebServerMessage = serde_json::from_str(&encoded).expect("decode");
        assert_eq!(decoded, message);

        let message = WebServerMessage::AgentStatusChanged {
            conversation_id: "conversation_1".to_string(),
            status: AgentStatus::Idle,
        };
        let encoded = serde_json::to_string(&message).expect("encode");
        assert!(encoded.contains(r#""type":"agent_status_changed""#));
        assert!(encoded.contains(r#""status":"idle""#));
        let decoded: WebServerMessage = serde_json::from_str(&encoded).expect("decode");
        assert_eq!(decoded, message);

        let message = WebServerMessage::ConversationReplay {
            conversation_id: "conversation_1".to_string(),
            items: vec![WebConversationItem {
                item_id: "item_1".to_string(),
                turn_id: Some("turn_1".to_string()),
                item: TurnTranscriptItem::UserText {
                    text: "hello".to_string(),
                },
            }],
        };
        let encoded = serde_json::to_string(&message).expect("encode");
        assert!(encoded.contains(r#""type":"conversation_replay""#));
        assert!(encoded.contains(r#""items":[{"#));
        let decoded: WebServerMessage = serde_json::from_str(&encoded).expect("decode");
        assert_eq!(decoded, message);

        let message = WebServerMessage::Error {
            code: Some(WebErrorCode::NotOnboarded),
            message: "Noema onboarding is incomplete.".to_string(),
        };
        let encoded = serde_json::to_string(&message).expect("encode");
        assert!(encoded.contains(r#""type":"error""#));
        assert!(encoded.contains(r#""code":"not_onboarded""#));
        let decoded: WebServerMessage = serde_json::from_str(&encoded).expect("decode");
        assert_eq!(decoded, message);
    }
}
